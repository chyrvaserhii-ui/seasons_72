/// Kigo (季語) — saijiki seasonal words paired to each of the 72 kō.
///
/// Saijiki are dictionaries of seasonal words used by haiku poets;
/// every word is anchored to a specific window of the year. Modern
/// saijiki such as the *Nyūmon Saijiki* and the *Kadokawa Haiku
/// Daisaijiki* organise their entries around the 24 sekki, but a
/// careful reader can sort kigo down to the 72 kō level — most words
/// have a peak of one or two five-day windows where they are most
/// vivid. The entries here pick three to five kigo per kō that a
/// poet would reach for first, with a brief note on the literary
/// tradition behind each.
library seasonal_kigo;

/// One seasonal word.
class KigoEntry {
  const KigoEntry({
    required this.japanese,
    required this.romaji,
    required this.glossUk,
    required this.glossEn,
    required this.noteUk,
    required this.noteEn,
  });

  /// Japanese form in kanji or kana, e.g. "東風", "鶯", "桜貝".
  final String japanese;

  /// Hepburn romaji, e.g. "kochi", "uguisu", "sakuragai".
  final String romaji;

  /// Brief Ukrainian gloss, e.g. "(східний весняний вітер)".
  final String glossUk;

  /// Brief English gloss, e.g. "(east spring wind)".
  final String glossEn;

  /// 1 sentence on the kigo's literary use — 60–120 chars Uk.
  final String noteUk;

  /// English version of [noteUk] — 60–120 chars.
  final String noteEn;
}

/// Collection of 3–5 kigo paired with a single kō.
class KigoPairing {
  const KigoPairing({
    required this.entries,
    required this.summaryUk,
    required this.summaryEn,
  });

  /// Three to five seasonal words ordered from most to least central.
  final List<KigoEntry> entries;

  /// One sentence framing what these words share — what mood / image
  /// they collectively summon in this kō. ≤180 chars Uk.
  final String summaryUk;

  /// English version of [summaryUk].
  final String summaryEn;
}

